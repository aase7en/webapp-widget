"use strict";
const puppeteer=require("puppeteer");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const {pathToFileURL}=require("node:url");
(async()=>{
 const output=process.env.HYBRID_QA_OUT||"/tmp/uth-weather-hybrid-20261105";
 fs.mkdirSync(output,{recursive:true});
 const browser=await puppeteer.launch({headless:true,executablePath:"/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",args:["--no-sandbox"]});
 let report={result:"UNKNOWN",cases:[],errors:[],requests:[],at:new Date().toISOString()};
 try{
  const page=await browser.newPage();
  await page.setViewport({width:1280,height:800,deviceScaleFactor:1});
  page.on("pageerror",e=>report.errors.push(e.message));
  page.on("console",m=>{if(m.type()==="error")report.errors.push(m.text())});
  page.on("request",r=>{if(/^https?:/.test(r.url()))report.requests.push(r.url())});
  await page.goto(pathToFileURL(path.join(__dirname,"index.html")).href,{waitUntil:"load"});
  await page.waitForFunction(()=>window.WeatherLedDemo&&window.WeatherHybridRenderer);
  await page.waitForFunction(()=>document.querySelector("#native-stage").shadowRoot?.querySelector(".hybrid-panel")?.querySelectorAll(".hybrid-day").length===4);
  async function geom(){
    return await page.evaluate(()=>{
      const stage=document.querySelector("#native-stage");
      const root=stage.shadowRoot,base=stage.getBoundingClientRect();
      const rect=(selector)=>{
       const el=root.querySelector(selector),r=el.getBoundingClientRect();
       return{x:+(r.left-base.left).toFixed(2),y:+(r.top-base.top).toFixed(2),w:+r.width.toFixed(2),h:+r.height.toFixed(2),right:+(r.right-base.left).toFixed(2),display:getComputedStyle(el).display};
      };
      const panel=root.querySelector(".hybrid-panel");
      const days=[...panel.querySelectorAll(".hybrid-day")];
      const overflow=days.filter(el=>el.scrollWidth>el.clientWidth+1||el.scrollHeight>el.clientHeight+1).map(el=>el.dataset.day);
      return {stage:[base.width,base.height],state:WeatherLedDemo.getState(),clock:rect("#time"),scene:rect("#scene"),icon:rect("#icon"),temp:rect(".temp"),forecast:rect(".hybrid-panel"),graph:rect(".graph"),reference:rect(".rf-board"),dayCount:days.length,days:days.map(el=>el.dataset.day),icons:panel.querySelectorAll(".hybrid-day .rf-weather-svg").length,metricIcons:panel.querySelectorAll(".hybrid-metric svg").length,metrics: [...panel.querySelectorAll(".hybrid-value")].map(n=>n.textContent), rain:days.map(el=>el.querySelector(".hybrid-rain").textContent),overflow,clockText:root.querySelector("#time").textContent,sceneLoaded:root.querySelector("#scene").naturalWidth>0,animationLoaded:root.querySelector("#icon").naturalWidth>0,posterLoaded:root.querySelector("#poster").naturalWidth>0};
    });
  }
  const initial=await geom();
  const crisp=await page.evaluate(()=>{
    const root=document.querySelector("#native-stage").shadowRoot;
    return {shadows:[...root.querySelectorAll(".hybrid-value")].map(el=>getComputedStyle(el).textShadow),filters:[...root.querySelectorAll(".hybrid-metric svg")].map(el=>getComputedStyle(el).filter)};
  });
  assert.ok(crisp.shadows.length===4&&crisp.shadows.every(x=>x==="none"),"All four numeric values have no glow blur");
  assert.ok(crisp.filters.length===4&&crisp.filters.every(x=>x==="none"),"All four pictograms have no bloom blur");
  report.cases.push({label:"metric-legibility-no-glow",crisp});
  assert.equal(initial.state.visual,"hybrid");
  assert.equal(initial.state.mode,"B");
  assert.deepEqual(initial.stage,[432,40]);
  assert.equal(initial.dayCount,4);
  assert.equal(initial.icons,4);
  assert.equal(initial.metricIcons,4);
  assert.ok(initial.graph.display==="none");
  assert.ok(initial.reference.display==="none");
  assert.deepEqual(initial.metrics,["40%","72%","36°","26°"]);
  assert.equal(initial.state.observedAt,null);
  assert.equal(initial.state.source,"SIMULATED / LOCAL FIXTURE");
  assert.equal(initial.clockText.includes(":"),true);
  assert.equal(initial.clock.x>=5&&initial.clock.x<=9,true);
  assert.deepEqual(initial.overflow,[]);
  assert.ok(initial.sceneLoaded&&initial.animationLoaded&&initial.posterLoaded);
  await (await page.$("#native-stage")).screenshot({path:path.join(output,"hybrid-first4-432x40.png")});
  report.cases.push({label:"hybrid-initial-A-to-B-4days",initial});
  await page.click("#next");
  const last=await geom();
  assert.equal(last.dayCount,3);assert.deepEqual(last.days,["4","5","6"]);
  assert.ok(last.graph.display==="none");
  assert.deepEqual(last.overflow,[]);
  await (await page.$("#native-stage")).screenshot({path:path.join(output,"hybrid-last3-432x40.png")});
  report.cases.push({label:"hybrid-last3",last});
  await page.evaluate(()=>{WeatherLedDemo.setPage(0);WeatherLedDemo.setIntervalSeconds(8);WeatherLedDemo.setPaused(false)});
  await page.waitForFunction(()=>WeatherLedDemo.getState().page===1,{timeout:11000,polling:200});
  report.cases.push({label:"automatic-8s-hybrid-rotation",passed:true});
  await page.evaluate(()=>WeatherLedDemo.setPaused(true));
  await page.click("#visual-luxury");
  await page.evaluate(()=>WeatherLedDemo.setCompact(false));
  const old=await geom();
  assert.ok(old.temp.x-initial.temp.x>=19&&old.temp.x-initial.temp.x<=23);
  assert.ok(old.icon.x-initial.icon.x>=20&&old.icon.x-initial.icon.x<=24);
  assert.ok(old.scene.w-initial.scene.w>=28&&old.scene.w-initial.scene.w<=32);
  assert.ok(Math.abs(old.clock.x-initial.clock.x)<0.2);
  report.cases.push({label:"original-clock-fixed-and-left-shift",legacy:{clock:old.clock,icon:old.icon,temp:old.temp,scene:old.scene},hybrid:{clock:initial.clock,icon:initial.icon,temp:initial.temp,scene:initial.scene}});
  await page.click("#visual-hybrid");
  assert.equal((await geom()).dayCount,4);
  await page.select("#scenario","edge");
  const heat=await geom();
  assert.deepEqual(heat.metrics,["100%","100%","45°","-9°"]);
  assert.equal(heat.dayCount,4);assert.ok(heat.icons===4);
  report.cases.push({label:"edge-100pct-negative-and-heat-colors",metrics:heat.metrics});
  await page.select("#scenario","missing");
  const missing=await geom();
  assert.deepEqual(missing.metrics,["0%","—","—","25°"]);
  assert.ok(missing.rain.some(v=>v==="0%"));
  report.cases.push({label:"missing-versus-zero",metrics:missing.metrics});
  await page.select("#scenario","normal");
  await page.setViewport({width:390,height:844,deviceScaleFactor:1,isMobile:true,hasTouch:true});
  await page.screenshot({path:path.join(output,"hybrid-mobile-390.png"),fullPage:true});
  const mobile=await page.evaluate(()=>({width:document.querySelector("#native-stage").getBoundingClientRect().width,pan:document.querySelector(".stage-scroll").scrollWidth>document.querySelector(".stage-scroll").clientWidth}));
  assert.equal(mobile.width,432);assert.equal(mobile.pan,true);
  report.cases.push({label:"iphone-mobile-scroll",mobile});
  const reduced=await browser.newPage();
  await reduced.emulateMediaFeatures([{name:"prefers-reduced-motion",value:"reduce"}]);
  await reduced.goto(pathToFileURL(path.join(__dirname,"index.html")).href,{waitUntil:"load"});
  const motion=await reduced.evaluate(()=>{const s=document.querySelector("#native-stage").shadowRoot;return{paused:WeatherLedDemo.getState().paused,icon:getComputedStyle(s.querySelector("#icon")).display,poster:getComputedStyle(s.querySelector("#poster")).display}});
  assert.equal(motion.paused,true);
  assert.equal(motion.icon,"none");assert.notEqual(motion.poster,"none");
  report.cases.push({label:"reduced-motion",motion});
  await reduced.close();
  assert.deepEqual(report.errors,[]);assert.deepEqual(report.requests,[]);
  report.result="PASS";
  console.log(JSON.stringify({result:"PASS",labels:report.cases.map(x=>x.label),layout:{originalTempX:old.temp.x,hybridTempX:initial.temp.x,originalIconX:old.icon.x,hybridIconX:initial.icon.x,originalSceneWidth:old.scene.w,hybridSceneWidth:initial.scene.w,clock:initial.clock.x},errors:report.errors}));
 }catch(e){report.result="FAIL";report.failure=e.stack;console.error(e.stack);process.exitCode=1}
 finally{fs.writeFileSync(path.join(output,"hybrid-qa-report.json"),JSON.stringify(report,null,2));await browser.close()}
})().catch(e=>{console.error(e.stack);process.exitCode=1});
