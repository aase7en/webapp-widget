function sparkSvg(path,id,description){
 // Only accept the simple polyline generated by historyPath; IDs are station-local.
 if(!path||!/^M[0-9.]+ [0-9.]+(?: L[0-9.]+ [0-9.]+)+$/.test(path)||!['s1','s2'].includes(id))return '<span class="unavailable-message" aria-label="No verified water history in the last seven days">NO DATA</span>';
 const pairs=Array.from(path.matchAll(/[ML]([0-9.]+) ([0-9.]+)/g));
 const first=pairs[0][1],last=pairs[pairs.length-1][1],gradient='water-fill-'+id;
 return `<svg class="spark" viewBox="0 0 340 125" role="img" aria-label="${description||'Observed water-level history within the last seven days'}"><defs><linearGradient id="${gradient}" x1="0" y1="0" x2="0" y2="1"><stop offset="0%" stop-color="#65efff" stop-opacity=".65"/><stop offset="100%" stop-color="#11b4f2" stop-opacity=".03"/></linearGradient></defs><path d="${path} L${last} 125 L${first} 125 Z" fill="url(#${gradient})"/><path d="${path}" fill="none" stroke="#9cf7ff" stroke-width="4" stroke-linejoin="round" stroke-linecap="round" /></svg>`;
}
function bankBadge(st,now=Date.now()){
 // Station level relative to bank is not an official flood warning. Stale
 // observations must never be presented as the current situation.
 const observed=Date.parse(st.observedAt);
 if(st.status==='historical'||(Number.isFinite(observed)&&now-observed>WATER_DISPLAY_MS))return {text:'ข้อมูลเก่าเกิน 6 ชม.',style:'unavailable stale-six-hour'};
 if(st.status!=='ok'||!Number.isFinite(observed)||observed>now+120000||st.datum!=='MSL'||!Number.isFinite(st.value)||!Number.isFinite(st.bankM))return {text:'รอข้อมูล',style:'unavailable'};
 if(st.value>st.bankM)return {text:'สูงกว่าตลิ่ง',style:'danger'};
 if(st.value===st.bankM)return {text:'ถึงตลิ่ง',style:'warn'};
 return {text:'ต่ำกว่าตลิ่ง',style:'unavailable'};
}
// Only a dimensionless fraction of the ground-to-lowest-bank interval;
 // not flood risk, reservoir capacity, or sluice-gate opening percentage.
function bankIntervalPercent(level,ground,bank,datum){
 if(datum!=='MSL'||![level,ground,bank].every(Number.isFinite)||bank<=ground||level<ground)return null;
 return Math.round(((level-ground)/(bank-ground))*1000)/10;
}
function trendCaption(reading,now=Date.now()){
 const vals=reading?.trendPoints,times=reading?.trendObservedAt;
 if(!Array.isArray(vals)||!Array.isArray(times)||vals.length!==times.length)return {label:'7D HISTORY',description:'No verified water history during the last seven days'};
 const minTime=now-7*86400000;
 const stamps=times.map((s,i)=>({ms:Date.parse(s),val:vals[i]}))
  .filter(x=>Number.isFinite(x.ms)&&x.ms>=minTime&&x.ms<=now&&Number.isFinite(x.val))
  .map(x=>x.ms).sort((a,b)=>a-b);
 if(stamps.length<2||stamps.at(-1)===stamps[0])return {label:'7D HISTORY',description:'Fewer than two time-distinct verified readings in the last seven days'};
 const hours=(stamps.at(-1)-stamps[0])/3600000;
 const coverage=hours<1?'<1H':hours<48?Math.round(hours)+'H':Math.round(hours/24)+'D';
 return {label:coverage+' / 7D',description:stamps.length+' observed readings cover '+hours.toFixed(1)+' hours within a seven-day lookback. Horizontal axis represents the actual observed time span; it does not imply seven complete days of measurements'};
}
// Direction is derived ONLY from a verified, time-matched observation series.
// The arrow is unknown if the graph does not actually contain the latest reading.
function observedDirection(st,now=Date.now()){
 const unknown={arrow:'—',cls:'unknown',description:'ไม่มีแนวโน้มที่ตรวจสอบได้'};
 const latest=Date.parse(st?.observedAt);
 if(st?.status!=='ok'||!Number.isFinite(latest)||latest>now+120000||
     now-latest>WATER_DISPLAY_MS||!Number.isFinite(st.value))return unknown;
 const vals=st.historyReading?.trendPoints,times=st.historyReading?.trendObservedAt;
 if(!Array.isArray(vals)||!Array.isArray(times)||vals.length!==times.length||
    vals.length<2||vals.length>30)return unknown;
 // Identical repeated timestamps may be collapsed. Conflicting values at the
 // SAME observation time cannot support a trustworthy public direction arrow.
 const byTime=new Map(),points=[];
 for(let i=0;i<vals.length;i++){
  const p={level:vals[i],ms:Date.parse(times[i])};
  if(!Number.isFinite(p.level)||!Number.isFinite(p.ms)||p.ms>now+120000||
      p.ms>latest+120000||p.ms<latest-7*86400000)continue;
  if(byTime.has(p.ms)){
   if(Math.abs(byTime.get(p.ms)-p.level)>1e-6)return unknown;
   continue;
  }
  byTime.set(p.ms,p.level);points.push(p);
 }
 points.sort((a,b)=>a.ms-b.ms);
 const last=points.at(-1);
 if(!last||Math.abs(last.ms-latest)>15*60000||Math.abs(last.level-st.value)>.05)return unknown;
 // Avoid describing a multi-day gap as a short-term rising/falling water level.
 const previous=points.slice(0,-1).filter(p=>last.ms-p.ms>=30*60000&&last.ms-p.ms<=6*3600000).at(-1);
 if(!previous)return unknown;
 const delta=last.level-previous.level;
 if(delta>.015)return {arrow:'↑',cls:'up',description:'ระดับน้ำสูงขึ้น '+Math.abs(delta).toFixed(2)+' เมตร ระหว่างค่าที่ตรวจวัด'};
 if(delta<-.015)return {arrow:'↓',cls:'down',description:'ระดับน้ำลดลง '+Math.abs(delta).toFixed(2)+' เมตร ระหว่างค่าที่ตรวจวัด'};
 return {arrow:'→',cls:'flat',description:'ระดับน้ำค่อนข้างคงที่ ระหว่างค่าที่ตรวจวัด'};
}
function escapeMarkup(v){
 return String(v??'').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
}
